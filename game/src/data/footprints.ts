/**
 * Where each landmark is solid (Luc's list, line 1: "collision on everything on the islands"), as the rules read it:
 * a grid of `FOOTPRINT_CELL` metres in the landmark's own frame (x to its right, -z its front, as the look builds
 * it), `#` where something stands at body height and `.` where you can walk. Row r covers z from
 * `z + r * FOOTPRINT_CELL`, column c covers x from `x + c * FOOTPRINT_CELL`.
 *
 * Measured from the drawings, not drawn by hand: `tests/look/footprints.ts` samples every surface between
 * `FOOTPRINT_BAND.low` and `.high` above the ground, and fills what is closed in. `tests/look/solids.test.ts` holds
 * this data to the drawings; when a drawing changes, `node --experimental-strip-types tests/look/footprints-print.ts`
 * prints it afresh.
 *
 * Not solid (`WALK_ON_LANDMARKS`): what you walk on or lie on. The dock, the bridge deck, the dam crest, the quarry
 * benches (their faces are walls already, `groundHeight`), the reed beds and the bedrolls.
 */
import type { LandmarkKind, NodeTypeId } from './types.ts';

/** Metres per footprint cell. */
export const FOOTPRINT_CELL = 0.5;
/** A surface between these heights above the ground is in the way of someone walking, metres. */
export const FOOTPRINT_BAND = { low: 0.3, high: 1.8 } as const;

/** Lower than the band for these: you could step over a fire ring's stones, but nobody should walk through a fire. */
export const FOOTPRINT_LOW: Partial<Record<LandmarkKind, number>> = { campfire: 0.02 };

export interface Footprint {
  /** The corner of the grid, in the landmark's frame, metres. */
  x: number;
  z: number;
  rows: string[];
}

